/**
 * Auto-registration names: `adjective-noun`, the way an operator would name a
 * colleague rather than a directory.
 *
 * The name is derived from the opencode `sessionID` by hash, not thrown from a
 * random source. That is the whole point: an id has to survive a restart of the
 * opencode process. A random name would change on every restart, the peer's
 * inbox would be orphaned under the old name, and the address other agents use
 * would drift. Hashing a stable id keeps the mesh serverless — no registry, no
 * name service, no coordination — while still giving two chats in one directory
 * two different, sayable names.
 *
 * The `attempt` counter is folded into the hash so a collision produces the
 * next pair instead of the same one; `Registry.allocateName` relies on that to
 * walk past names a live peer already holds.
 */

