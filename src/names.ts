/**
 * The name an auto-registered agent gets for this session. Deterministic:
 * the same `seed` and `attempt` always produce the same name, in any process,
 * which is what makes the id survive a restart.
 */
export function agentName(seed: string, attempt = 1): string {
  const digest = createHash("sha256").update(`${seed}:${attempt}`).digest()
  const left = ADJECTIVES[digest.readUInt16BE(0) % ADJECTIVES.length]
  const right = NOUNS[digest.readUInt16BE(2) % NOUNS.length]
  return `${left}-${right}`
}
